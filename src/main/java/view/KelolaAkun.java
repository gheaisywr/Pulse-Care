    private void tampilkanAkun(String kataKunci, String role) {

    DefaultTableModel model = new DefaultTableModel(
        new Object[]{"NIP", "Nama Lengkap", "Role", "Informasi Tambahan", "Status"}, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    try {
        List<Akun> daftar = adminController.semua(kataKunci, role);
            if (daftar.isEmpty()) {
        tabelKelolaAkun.setModel(model);

        JOptionPane.showMessageDialog(
            this,
            "Data akun yang kamu cari tidak ditemukan!",
            "Data Tidak Ditemukan",
            JOptionPane.INFORMATION_MESSAGE
        );

        return;
    }
        for (Akun akun : daftar) {
            model.addRow(new Object[]{
                akun.getNip(),
                akun.getNama(),
                akun.getRole(),
                akun.getDetail(),
                akun.getStatus()
            });
        }

        tabelKelolaAkun.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Gagal mengambil data akun: " + e.getMessage()
        );
    }
}
