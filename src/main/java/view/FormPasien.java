    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            String nama = kolomNama.getText().trim();
            String nik = kolomIdentitas.getText().trim();
            String tanggal = kolomTanggalLahir.getText().trim();

            String jenisKelamin = kolomSpesialisasi.getSelectedItem().toString();
            String statusBpjs = kolomShift.getSelectedItem().toString();

            // Validasi input kosong
            if (nama.isEmpty() || nama.equals("Masukkan Nama lengkap")
                    || nik.isEmpty() || nik.equals("Masukkan NIK")
                    || tanggal.isEmpty() || tanggal.equals("YYYY-MM-DD")
                    || jenisKelamin.equals("Pilih Jenis Kelamin")
                    || statusBpjs.equals("Pilih Status BPJS")) {

                JOptionPane.showMessageDialog(this,
                        "Semua data pasien wajib diisi!");
                return;
            }

            // Validasi NIK
            if (!nik.matches("\\d{16}")) {
                JOptionPane.showMessageDialog(this,
                        "NIK harus terdiri dari 16 digit angka!");
                return;
            }

            // Membuat objek pasien
            model.Pasien pasien = new model.Pasien();

            pasien.setIdPasien(new PasienController().idBerikutnya());
            pasien.setNamaLengkap(nama);
            pasien.setNik(nik);
            pasien.setTanggalLahir(java.time.LocalDate.parse(tanggal));
            pasien.setJenisKelamin(jenisKelamin.toLowerCase());
            pasien.setStatusBpjs(statusBpjs.toLowerCase());

            // Menyimpan pasien
            PasienController controller = new PasienController();

            if (controller.tambah(pasien)) {
                JOptionPane.showMessageDialog(this,
                        "Data pasien berhasil disimpan!");

                dispose();
            } else {
                JOptionPane.showMessageDialog(this,
                        "Data pasien gagal disimpan!");
            }

        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Format tanggal harus YYYY-MM-DD!");

        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Terjadi kesalahan database: " + e.getMessage());

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Terjadi kesalahan: " + e.getMessage());
        }
    
    }//GEN-LAST:event_btnSimpanActionPerformed

